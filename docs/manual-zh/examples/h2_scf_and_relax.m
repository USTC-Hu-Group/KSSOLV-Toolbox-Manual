% 中文用户手册：H2 的自洽计算与原子位置优化。
% 在手册仓库根目录执行 run('docs/manual-zh/examples/h2_scf_and_relax.m')。
% 本例仅使用 CPU；可由 MATLAB -nojvm -batch 执行。

manualPaths = manual_example_setup();
exampleDirectory = manualPaths.exampleDirectory;
outputDirectory = manualPaths.outputDirectory;
repositoryDirectory = manualPaths.toolboxRoot;
KSSOLV.startup();
rng(7, 'twister');
diary(fullfile(outputDirectory, 'h2-nojvm.log'));
cleanupDiary = onCleanup(@() diary('off'));
fprintf('MATLAB: %s\nArchitecture: %s\nJVM: %d\n', ...
    version, computer('arch'), usejava('jvm'));

pseudopotential.PpType('default');
molecule = example.structure.H2();
molecule.ecut = 20;                 % Hartree
molecule.funct = 'PBE';
scfOptions = options.SCF('force', true);
scfOptions.enableGPU = false;
scfOptions.enableParallelPool = false;

initialBondBohr = norm(molecule.xyzlist(1,:) - molecule.xyzlist(2,:));
initialGeometry = struct('supercell', molecule.supercell, ...
    'xyzlist', molecule.xyzlist);
[molecule, H, X, scfInfo] = scf(molecule, scfOptions);
relaxOptions = options.Relaxation();
relaxOptions.relaxmethod = 'fminunc';
relaxOptions.relaxtol = 1e-4;
relaxOptions.maxrelaxiter = 100;
relaxOptions.enableGPU = false;
relaxOptions.enableParallelPool = false;
[optimizedMolecule, ~, ~, relaxInfo] = ...
    geometryoptimization.relaxatoms(molecule, relaxOptions, H, X);
optimizedBondBohr = norm(optimizedMolecule.xyzlist(1,:) - ...
    optimizedMolecule.xyzlist(2,:));
optimizedGeometry = struct('supercell', optimizedMolecule.supercell, ...
    'xyzlist', optimizedMolecule.xyzlist);
report = struct('MATLAB', version, 'Architecture', computer('arch'), ...
    'JVM', usejava('jvm'), 'Functional', 'PBE', 'Pseudopotential', 'default', ...
    'EcutHartree', 20, 'SCFConverged', logical(scfInfo.converge), ...
    'SCFIterations', numel(scfInfo.Etotvec), ...
    'SCFEnergyHartree', scfInfo.Etot, ...
    'SCFFinalError', scfInfo.SCFerrvec(end), ...
    'InitialBondBohr', initialBondBohr, ...
    'InitialBondAngstrom', initialBondBohr * bohr2ang, ...
    'OptimizedBondBohr', optimizedBondBohr, ...
    'OptimizedBondAngstrom', optimizedBondBohr * bohr2ang, ...
    'RelaxationInfo', relaxInfo);
writelines(jsonencode(report, PrettyPrint=true), ...
    fullfile(outputDirectory, 'h2-nojvm-results.json'));
save(fullfile(outputDirectory, 'h2-nojvm-results.mat'), ...
    'report', 'scfInfo', 'relaxInfo', 'molecule', 'optimizedMolecule', ...
    'initialGeometry', 'optimizedGeometry');
writematrix(optimizedGeometry.xyzlist, ...
    fullfile(outputDirectory, 'h2-final-coordinates-bohr.csv'));
disp(report);
clear cleanupDiary;
