#!/usr/bin/env python3
"""Create the cover's orthographic silicon diamond lattice from silicon.cif.

The source cell is repeated three times along [100], with boundary sites
included. Lines join first neighbours; four teal bonds show one tetrahedron.
Only Python's standard library is required. Output is editable vector TikZ.
"""

from pathlib import Path
import hashlib
import itertools
import json
import math


def main():
    manual = Path(__file__).resolve().parents[1]
    source = manual / 'examples' / 'silicon.cif'
    lines = source.read_text().splitlines()
    lattice = float(next(line.split()[1] for line in lines
                         if line.startswith('_cell_length_a ')))
    for axis in ('b', 'c'):
        value = float(next(line.split()[1] for line in lines
                           if line.startswith(f'_cell_length_{axis} ')))
        assert math.isclose(value, lattice, abs_tol=1e-10)
    for angle in ('alpha', 'beta', 'gamma'):
        value = float(next(line.split()[1] for line in lines
                           if line.startswith(f'_cell_angle_{angle} ')))
        assert math.isclose(value, 90, abs_tol=1e-10)
    fractional = [tuple(float(v) for v in line.split()[2:5])
                  for line in lines if line.startswith('Si')]
    assert all(abs(4*v-round(4*v)) < 1e-10 for p in fractional for v in p)
    basis = [tuple(round(4*v) for v in p) for p in fractional]
    fcc = {(0, 0, 0), (0, 2, 2), (2, 0, 2), (2, 2, 0)}
    diamond = fcc | {tuple((v+1) % 4 for v in p) for p in fcc}
    assert len(basis) == 8 and set(basis) == diamond
    sites = sorted({tuple(p[i] + 4 * shift[i] for i in range(3))
                    for p in basis
                    for shift in itertools.product(range(-1, 4), repeat=3)
                    if all(0 <= p[i] + 4 * shift[i] <= (12, 4, 4)[i]
                           for i in range(3))})
    bonds = [(a, b) for a, b in itertools.combinations(sites, 2)
             if sum((a[i] - b[i]) ** 2 for i in range(3)) == 3]
    center = (5, 1, 1)
    neighbours = [b if a == center else a for a, b in bonds
                  if center in (a, b)]
    assert len(neighbours) == 4
    for a, b in itertools.combinations(neighbours, 2):
        assert sum((a[i] - center[i]) * (b[i] - center[i])
                   for i in range(3)) == -1
    for p in sites:
        if all(0 < p[i] < (12, 4, 4)[i] for i in range(3)):
            assert sum(p in bond for bond in bonds) == 4

    azimuth, elevation = map(math.radians, (20, 14))
    ca, sa, ce, se = (math.cos(azimuth), math.sin(azimuth),
                      math.cos(elevation), math.sin(elevation))

    def project(p):
        x, y, z = (v / 4 for v in p)
        return ca*x + sa*y, sa*se*x - ca*se*y + ce*z

    def depth(p):
        x, y, z = (v / 4 for v in p)
        return sa*ce*x - ca*ce*y - se*z

    scale = 128 / (3*ca + sa)
    bottom = min(project(p)[1] for p in sites)

    def point(p):
        x, y = project(p)
        return f'({17 + scale*x:.5f},{26 + scale*(y-bottom):.5f})'

    output = [
        '% Generated by generate_cover_silicon.py; coordinates are page millimetres.',
        '% Silicon diamond, 3 x 1 x 1 conventional cells, orthographic projection.',
        r'\begin{scope}[shift={(current page.south west)},x=1mm,y=1mm]',
    ]
    # A quiet cell outline conveys translational symmetry without a planar grid.
    for cell in range(3):
        corners = [(4*(cell+x), 4*y, 4*z)
                   for x, y, z in itertools.product((0, 1), repeat=3)]
        for a, b in itertools.combinations(corners, 2):
            if sum(a[i] != b[i] for i in range(3)) == 1:
                output.append(r'\draw[titleblue!20,line width=.32pt] '
                              + point(a) + ' -- ' + point(b) + ';')
    low, high = min(map(depth, sites)), max(map(depth, sites))
    primitives = []
    for a, b in bonds:
        highlighted = center in (a, b)
        d = (depth(a)+depth(b))/2
        tone = round(36 + 35*(d-low)/(high-low))
        colour = 'teal!95!brand' if highlighted else f'titleblue!{tone}!white'
        width = '1.3pt' if highlighted else '.95pt'
        primitives.append((d, 0, [
            r'\draw[white,line width=2.0pt,line cap=round] '
            + point(a) + ' -- ' + point(b) + ';',
            rf'\draw[{colour},line width={width},line cap=round] '
            + point(a) + ' -- ' + point(b) + ';']))
    for p in sites:
        d = depth(p)
        tone = round(42 + 42*(d-low)/(high-low))
        radius = 1.3 + .2*(d-low)/(high-low)
        x, y = project(p)
        px, py = 17+scale*x, 26+scale*(y-bottom)
        primitives.append((d, 1, [
            rf'\filldraw[fill=titleblue!{tone}!brand,draw=white,line width=.45pt] '
            + point(p) + f' circle[radius={radius:.3f}mm];',
            rf'\fill[white,opacity=.55] ({px-.32:.5f},{py+.34:.5f}) '
            + 'circle[radius=.31mm];']))
    # Paint complete atom discs over the bond layer so connections never slice
    # the projected spheres; depth ordering is retained within each layer.
    for _, _, commands in sorted(primitives, key=lambda item: (item[1], item[0])):
        output.extend(commands)
    output.append(r'\end{scope}')
    destination = manual / 'figures' / 'cover-silicon.tex'
    destination.write_text('\n'.join(output) + '\n')
    report = {
        'source': 'docs/manual-zh/examples/silicon.cif',
        'sourceSHA256': hashlib.sha256(source.read_bytes()).hexdigest(),
        'structure': 'silicon diamond cubic', 'conventionalCells': [3, 1, 1],
        'closedBoundarySites': len(sites), 'firstNeighbourBonds': len(bonds),
        'latticeConstantAngstrom': lattice,
        'firstNeighbourDistanceAngstrom': math.sqrt(3)*lattice/4,
        'highlightedCoordination': 4,
        'tetrahedralBondAngleDegrees': math.degrees(math.acos(-1/3)),
        'orthographicAzimuthDegrees': 20, 'orthographicElevationDegrees': 14,
        'projectedWidthMm': 128,
        'projectedHeightMm': scale*(max(project(p)[1] for p in sites)-bottom),
    }
    report_path = manual.parents[1] / 'output' / 'cover-design' / 'geometry.json'
    report_path.parent.mkdir(parents=True, exist_ok=True)
    report_path.write_text(json.dumps(report, indent=2) + '\n')
    print(json.dumps(report, indent=2))


if __name__ == '__main__':
    main()
